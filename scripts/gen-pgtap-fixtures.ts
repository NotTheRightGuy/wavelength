// Generates supabase/tests/003_parity.test.sql from the shared engine fixtures.
// Run with: pnpm db:fixtures
import { readFileSync, writeFileSync } from 'node:fs'

type Scenario = {
  name: string
  teams: number
  winning: number
  turns: [number, number[]][]
  expect: { scores: number[]; active: number; phase: string; winners: number[] }
}

const scenarios: Scenario[] = JSON.parse(readFileSync('src/game-engine/fixtures/team-turns.json', 'utf8'))
const esc = (s: string) => s.replace(/'/g, "''")
const idsOf = (positions: number[]) => `array[${positions.map((p) => `v_ids[${p + 1}]`).join(', ')}]::uuid[]`

const blocks = scenarios.map((s, i) => {
  const label = esc(s.name)
  const room = `(select room from parity_rooms where n = ${i})`
  const seatAt = (pos: number) => `(select id from seats where room_id = ${room} and position = ${pos})`
  const winners = s.expect.winners.length
    ? `array[${s.expect.winners.map(seatAt).join(', ')}]::uuid[]`
    : `'{}'::uuid[]`
  return `
-- ${label}
do $$
declare v_room uuid; v_ids uuid[];
begin
  insert into rooms (code, host_session, mode, winning_score, status)
    values ('PAR${i}', gen_random_uuid(), 'teams', ${s.winning}, 'playing') returning id into v_room;
  insert into seats (room_id, session_id, position, name, color, members)
    select v_room, gen_random_uuid(), p, 'T' || p, '#000', array['m'] from generate_series(0, ${s.teams - 1}) p;
  select array_agg(id order by position) into v_ids from seats where room_id = v_room;
  update rooms set game = jsonb_build_object('phase', 'playing', 'active', v_ids[1], 'winners', '[]'::jsonb) where id = v_room;
  ${s.turns.map(([pts, bonus]) => `perform apply_team_turn(v_room, ${pts}, ${bonus.length ? idsOf(bonus) : `'{}'::uuid[]`});`).join('\n  ')}
  insert into parity_rooms values (${i}, v_room);
end $$;
select is(
  (select array_agg(score order by position) from seats where room_id = ${room}),
  array[${s.expect.scores.join(',')}]::int[], '${label}: scores');
select is(
  (select (game->>'active')::uuid from rooms where id = ${room}),
  ${seatAt(s.expect.active)}, '${label}: active team');
select is((select game->>'phase' from rooms where id = ${room}), '${s.expect.phase}', '${label}: phase');
select is(
  (select coalesce(array_agg(w::uuid order by o), '{}'::uuid[])
     from rooms, jsonb_array_elements_text(game->'winners') with ordinality as t(w, o) where rooms.id = ${room}),
  ${winners}, '${label}: winners');
`
})

const header = `-- GENERATED by scripts/gen-pgtap-fixtures.ts from src/game-engine/fixtures/team-turns.json. Do not edit.
begin;
select plan(${scenarios.length * 4});
create temp table parity_rooms (n int primary key, room uuid not null);
`
writeFileSync('supabase/tests/003_parity.test.sql', `${header}${blocks.join('')}\nselect * from finish();\nrollback;\n`)
console.log(`wrote supabase/tests/003_parity.test.sql (${scenarios.length} scenarios)`)
